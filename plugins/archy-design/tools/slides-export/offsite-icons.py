# An arrow's viewBox is its own width, so one file per width. Every one is blue-tint-300.
ARROWS = {"arrow-right-140": 140, "arrow-right-90": 90, "arrow-right-80": 80}

ICON = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="{px}" '
        'height="{px}" fill="none" stroke="{c}" stroke-width="1.5" '
        'stroke-linecap="round" stroke-linejoin="round">{body}</svg>')

ARROW = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} 16" width="{w}" '
         'height="16"><path d="M{x0} 8 H{x1}" fill="none" stroke="{c}" stroke-width="2" '
         'stroke-linecap="round"/><path d="M{hx} 2 L{tip} 8 L{hx} 14 Z" fill="{c}"/></svg>')


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, spec in ICONS.items():
        colour, ds = spec[0], spec[1]
        shapes = spec[2] if len(spec) > 2 else []
        for d in ds:
            # The silent failure of the extraction route is an empty `d`: a blank square
            # that reads as a spacing bug rather than a missing icon.
            if not d.strip():
                raise SystemExit("icon %s has an empty path" % name)
        body = "".join('<path d="%s"/>' % d for d in ds)
        body += "".join("<%s %s/>" % (tag, attrs) for tag, attrs in shapes)
        svg = ICON.format(px=56, c=colour, body=body)
        path = os.path.join(OUT, name + ".png")
        cairosvg.svg2png(bytestring=svg.encode("utf-8"), write_to=path,
                         output_width=56 * SCALE, output_height=56 * SCALE)
        print("  %-24s %s" % (name, os.path.relpath(path, DIR)))
    for name, w in ARROWS.items():
        svg = ARROW.format(w=w, x0=1, x1=w - 14, hx=w - 15, tip=w - 1, c=TINT3)
        path = os.path.join(OUT, name + ".png")
        cairosvg.svg2png(bytestring=svg.encode("utf-8"), write_to=path,
                         output_width=w * SCALE, output_height=16 * SCALE)
        print("  %-24s %s" % (name, os.path.relpath(path, DIR)))


if __name__ == "__main__":
    main()
